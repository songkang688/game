/** 残局解开时要朗读的整句话。 */
export function puzzleSolvedSpeechLine(hintUsed: boolean): string {
  return hintUsed
    ? "解开啦！下次不用提示，能拿三颗星哦！"
    : "太棒了！不用提示就解开，三颗星到手！";
}

/** 残局失败时要朗读的整句话：报第一步正解方向（列/行从 1 数起），没有就纯安抚。 */
