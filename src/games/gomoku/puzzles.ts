type P = [number, number];

interface BasePuzzle {
  name: string;
  tip: string;
  moves: number;
  black: P[];
  white: P[];
}

/**
 * 对称变换(9×9 棋盘,中心对称基准 8):
 * 0 原样 | 1 左右镜像 | 2 上下镜像 | 3 旋转180°
 * 4 主对角转置 | 5 旋转90° | 6 旋转270° | 7 副对角转置
 * 变换后再平移 (dx, dy)。
 */
function applySym(p: P, sym: number): P {
  const [x, y] = p;
  const c = 8;
  switch (sym) {
    case 1: return [c - x, y];
    case 2: return [x, c - y];
    case 3: return [c - x, c - y];
    case 4: return [y, x];
    case 5: return [c - y, x];
    case 6: return [y, c - x];
    case 7: return [c - y, c - x];
    default: return [x, y];
  }
}

interface VariantSpec {
  /** 变体名(与基础局名组合保证唯一) */
  name: string;
  sym: number;
  dx: number;
  dy: number;
  tip?: string;
}

function buildVariant(base: BasePuzzle, v: VariantSpec, theme: number): PuzzleDef {
  const map = (p: P): P => {
    const [x, y] = applySym(p, v.sym);
    return [x + v.dx, y + v.dy];
  };
  return {
    name: v.name,
    tip: v.tip ?? base.tip,
    size: 9,
    black: base.black.map(map),
    white: base.white.map(map),
    moves: base.moves,
    theme,
  };
}

