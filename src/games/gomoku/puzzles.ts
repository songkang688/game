export interface PuzzleDef {
  name: string;
  tip: string;
  /** 棋盘大小(一年级用 9×9) */
  size: number;
  black: Array<[number, number]>;
  white: Array<[number, number]>;
  /** 黑棋最多可以走几步 */
  moves: number;
  /** 所属主题序号(0-8) */
  theme: number;
  /** 解法分类(1.2 起,第 100–188 题带) */
  solutionKind?: SolutionKind;
  /** 首手解集:所有「下这一手仍然必胜」的点(1.2 起,第 100–188 题带) */
  solutions?: Array<[number, number]>;
}

/** 这道题算哪一类解法:老题按手数推,新题读标注 */
export function puzzleKind(p: PuzzleDef): SolutionKind {
  if (p.solutionKind) return p.solutionKind;
  if (p.moves <= 2) return "unique";
  if (p.moves === 3) return "mate3";
  return p.moves === 4 ? "mate4" : "mate5";
}

