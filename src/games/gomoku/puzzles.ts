/** 把残局摆到新棋盘上（黑=1 白=2） */
export function puzzleBoard(p: PuzzleDef): Board {
  const b = makeBoard(p.size);
  for (const [x, y] of p.black) setCell(b, x, y, 1);
  for (const [x, y] of p.white) setCell(b, x, y, 2);
  return b;
}
