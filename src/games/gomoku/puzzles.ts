/**
 * 一道题「靠什么解开」。
 * - unique 唯一胜点:整盘只有一个点能赢;
 * - mate3 / mate4 / mate5:三手 / 四手 / 五手连续先手杀;
 * - forbidden 抓禁手:最顺的那条杀法中途要踩黑棋禁手,开着禁手规则就得换一条;
 * - sacrifice 弃子引杀:首手那颗子最后不进五连,它只负责把白棋调到没用的地方。
 */
export type SolutionKind = "unique" | "mate3" | "mate4" | "mate5" | "forbidden" | "sacrifice";

