/** 每一章的起止关号(从 1 数起) */
function chapterRanges(): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  let from = 1;
  for (const ch of CHAPTERS) {
    out.push([from, from + ch.size - 1]);
    from += ch.size;
  }
  return out;
}

