      "钩子收回来以后会停在放绳时的角度接着摆,连着钩同一侧的目标可以省掉大半等待时间。",
      "商店里花的是这一趟挖到的金币,买了就等于先扣分,得靠它省下来的时间赚回来。",
      "过关线是目标金额,三星线是目标的一倍半;先稳稳过线,再拿剩下的时间冲星。",
      "无尽矿井越往下照明圈越小,但永远看得清顶上那行字;每挖穿五层会有一次三选一的补给。",
